func TestFindStructFile(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "zz_dbaas_types.go")
	if err := os.WriteFile(path, []byte(fixtureSrc), 0o644); err != nil {
		t.Fatalf("write fixture: %v", err)
	}
	// Decoy file that should be skipped (no matching struct).
	if err := os.WriteFile(filepath.Join(dir, "zz_other_types.go"), []byte("package v1alpha1\n"), 0o644); err != nil {
		t.Fatalf("write decoy: %v", err)
	}

	got, err := findStructFile(dir, "DbaasParameters")
	if err != nil {
		t.Fatalf("findStructFile: %v", err)
	}
	if got != path {
		t.Errorf("findStructFile = %q, want %q", got, path)
	}

	missing, err := findStructFile(dir, "NotAStruct")
	if err != nil {
		t.Fatalf("findStructFile (missing): %v", err)
	}
	if missing != "" {
		t.Errorf("expected empty path for missing struct, got %q", missing)
	}

	gone, err := findStructFile(filepath.Join(dir, "does-not-exist"), "Anything")
	if err != nil {
		t.Fatalf("findStructFile on missing dir: %v", err)
	}
	if gone != "" {
		t.Errorf("expected empty path for missing dir, got %q", gone)
	}
}

// mustHaveMarkerBefore asserts that `marker` appears as the line immediately
// preceding the field declaration `fieldName` in `src`.
func mustHaveMarkerBefore(t *testing.T, src, marker, fieldName string) {
	t.Helper()
	lines := strings.Split(src, "\n")
	for i, line := range lines {
		// Match the field line: leading tab, then "<FieldName> ".
		if !strings.HasPrefix(line, "\t"+fieldName+" ") {
			continue
		}
		if i == 0 {
			t.Fatalf("field %s is on the first line", fieldName)
		}
		prev := strings.TrimSpace(lines[i-1])
		if prev != marker {
			t.Errorf("field %s: previous line = %q, want %q", fieldName, prev, marker)
		}
		return
	}
	t.Errorf("field %s not found in source", fieldName)
}

// extractStruct returns the substring of src bounded by the type declaration
// `type <name> struct {` through the matching `}`.
func extractStruct(t *testing.T, src, name string) string {
	t.Helper()
	header := "type " + name + " struct {"
	start := strings.Index(src, header)
	if start < 0 {
		t.Fatalf("struct %s not found", name)
	}
	end := strings.Index(src[start:], "\n}")
	if end < 0 {
		t.Fatalf("struct %s not closed", name)
	}
	return src[start : start+end+2]
}
