// fixtureSrc mirrors the upjet v2.2.0 emission shape for
// apis/cluster/dbaas/v1alpha1/zz_dbaas_types.go: a top-level *Parameters
// struct with `+kubebuilder:validation:Optional` markers preceding each
// field, plus a nested *Parameters struct that must be left alone.
const fixtureSrc = `// Code generated by upjet. DO NOT EDIT.

package v1alpha1

type DbaasInitParameters struct {

	// (String) DBaaS name
	Name *string ` + "`json:\"name,omitempty\" tf:\"name,omitempty\"`" + `
}

type DbaasParameters struct {

	// (String) Billing period
	// +kubebuilder:validation:Optional
	BillingPeriod *string ` + "`json:\"billingPeriod,omitempty\" tf:\"billing_period,omitempty\"`" + `

	// (String) DBaaS engine ID
	// +kubebuilder:validation:Optional
	EngineID *string ` + "`json:\"engineId,omitempty\" tf:\"engine_id,omitempty\"`" + `

	// (String) DBaaS name
	// +kubebuilder:validation:Optional
	Name *string ` + "`json:\"name,omitempty\" tf:\"name,omitempty\"`" + `

	// (Attributes) Network configuration (block)
	// +kubebuilder:validation:Optional
	Network *NetworkParameters ` + "`json:\"network,omitempty\" tf:\"network,omitempty\"`" + `

	// (String) Zone
	// +kubebuilder:validation:Optional
	Zone *string ` + "`json:\"zone,omitempty\" tf:\"zone,omitempty\"`" + `
}

type NetworkParameters struct {

	// (String) Subnet URI ref
	// +kubebuilder:validation:Optional
	SubnetURIRef *string ` + "`json:\"subnetUriRef,omitempty\" tf:\"subnet_uri_ref,omitempty\"`" + `
}
`

func TestPromoteFieldsInFile_FlipsOnlyTopLevelRequiredFields(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "zz_dbaas_types.go")
	if err := os.WriteFile(path, []byte(fixtureSrc), 0o644); err != nil {
		t.Fatalf("write fixture: %v", err)
	}

	required := map[string]struct{}{
		"engine_id": {},
		"name":      {},
		"network":   {},
		"zone":      {},
		// billing_period intentionally omitted — must stay Optional.
	}

	changed, err := promoteFieldsInFile(path, "DbaasParameters", required)
	if err != nil {
		t.Fatalf("promoteFieldsInFile: %v", err)
	}
	if !changed {
		t.Fatalf("expected file to be modified, got changed=false")
	}

	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read result: %v", err)
	}
	out := string(got)

	dbaasParams := extractStruct(t, out, "DbaasParameters")
	networkParams := extractStruct(t, out, "NetworkParameters")

	// Top-level required fields are Required.
	for _, field := range []string{"EngineID", "Name", "Network", "Zone"} {
		mustHaveMarkerBefore(t, dbaasParams, requiredMarker, field)
	}

	// Top-level non-required field stays Optional.
	mustHaveMarkerBefore(t, dbaasParams, optionalMarker, "BillingPeriod")

	// Nested NetworkParameters.SubnetURIRef must be untouched (Optional).
	mustHaveMarkerBefore(t, networkParams, optionalMarker, "SubnetURIRef")

	// Init struct is untouched.
	if strings.Contains(extractStruct(t, out, "DbaasInitParameters"), requiredMarker) {
		t.Errorf("DbaasInitParameters unexpectedly modified")
	}

	// Idempotent: a second run must report no change.
	changed2, err := promoteFieldsInFile(path, "DbaasParameters", required)
	if err != nil {
		t.Fatalf("second run: %v", err)
	}
	if changed2 {
		t.Errorf("second run modified the file; expected idempotent no-op")
	}
}

func TestPromoteFieldsInFile_NoMatchingFieldsLeavesFileUntouched(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "zz_dbaas_types.go")
	if err := os.WriteFile(path, []byte(fixtureSrc), 0o644); err != nil {
		t.Fatalf("write fixture: %v", err)
	}
	orig, _ := os.ReadFile(path)

	changed, err := promoteFieldsInFile(path, "DbaasParameters", map[string]struct{}{
		"nonexistent_field": {},
	})
	if err != nil {
		t.Fatalf("promoteFieldsInFile: %v", err)
	}
	if changed {
		t.Errorf("expected no change")
	}

	got, _ := os.ReadFile(path)
	if !bytes.Equal(got, orig) {
		t.Errorf("file content changed despite changed=false")
	}
}

